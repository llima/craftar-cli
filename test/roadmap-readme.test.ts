import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

// The user's ruling of 2026-11-02: Phase 1 and Phase 2 are closed; Later is unchanged.
// A Windows checkout holds the README with CRLF; every assertion below reads it as LF.
const README = readFileSync(path.resolve(__dirname, "../README.md"), "utf8").replace(/\r\n/g, "\n");
const lines = README.split("\n");
const phase = (n: number): string => lines.find((l) => l.startsWith(`Phase ${n} `))!;

describe("README — the roadmap with phases 1 and 2 closed", () => {
  it("Phase 0, 1 and 2 read done, none reads in progress or has a Next:", () => {
    for (const n of [0, 1, 2]) {
      expect(phase(n)).toMatch(/^Phase \d — [a-z ]+ \(done\)/);
      expect(phase(n)).not.toContain("in progress");
      expect(phase(n)).not.toContain("Next:");
    }
    expect(lines.filter((l) => /^Phase \d/.test(l))).toHaveLength(3);
  });

  it("Phase 1's shipped list ends with Kiro agents' permissions and craftar settings apply", () => {
    expect(phase(1)).toContain("; Kiro agents' `permissions` (`permissions.rules` derived from the agent's tools, so kiro-cli 2.37 no longer rewrites the file); ");
    expect(phase(1).endsWith("; `craftar settings apply` (the generated `hooks` and `env` names merged into `.claude/settings.json`, only when a person types it).")).toBe(true);
  });

  it("Later keeps the Agent Plugin packaging once spec 61's three slices shipped", () => {
    const later = lines.filter((l) => l.startsWith("Later:"));
    expect(later).toEqual(["Later: the Agent Plugin packaging of `craftar mcp`."]);
  });

  // Since 1.0.0 the status line is a short paragraph (the user's ruling of 2026-11-06); the old status line test is removed.
});


// The user's ruling of 2026-11-06: the README status becomes a short paragraph.
const STATUS = "> Status: **1.3.0** — phases 0, 1 and 2 done: the foundations, the client profile and the environment. `import`, `sync`, `status`, `diff`, `explain` and `ls` work end to end for the `claude-code` and `kiro` targets and are validated byte for byte against a real workspace (see *Oracle*); `agents-md` is emitted too, since 1.1.0 `cursor`, `copilot` and `agent-skills`, since 1.2.0 `codex` and `antigravity`, and since 1.3.0 `gemini` (see *Targets*). A Forge declares the `schema:` it needs, from 1 to 17, each level opt-in and refused by an older craftar. Every command is in *Commands*, what each release changed is in *Upgrading*, and what 1.0.0 promises to keep stable is in *Compatibility*.";
const h2 = lines.filter((l) => l.startsWith("## "));

describe("README — 1.0.0", () => {
  it("the status line is the 1.0.0 paragraph", () => {
    expect(lines[4]).toBe(STATUS);
  });

  it("one Compatibility section, between the Roadmap and Upgrading", () => {
    expect(h2.filter((l) => l === "## Compatibility")).toHaveLength(1);
    expect(h2[h2.indexOf("## Compatibility") - 1]).toBe("## Roadmap (from the functional spec)");
    expect(h2[h2.indexOf("## Compatibility") + 1]).toBe("## Upgrading");
  });

  it("it states the four promises, what is outside, the bytes rule and every Forge schema", () => {
    const compatStart = README.indexOf("## Compatibility");
    const compatEnd = README.indexOf("\n## ", compatStart + 1);
    const compat = README.slice(compatStart, compatEnd);
    expect(compat).toContain("semantic versioning");
    expect(compat).toContain("**Commands, flags and exit codes**");
    expect(compat).toContain("**The tooling contracts**");
    expect(compat).toContain("**Forges**");
    expect(compat).toContain("**`craftar.lock` and the registry**");
    expect(compat).toContain("Not covered");
    expect(compat).toContain("the routes of `craftar ui`");
    expect(compat).toContain("the refusals before it starts serving");
    expect(compat).toContain("Each exit code keeps its meaning, but a new or changed warning or check can change what a run exits with under `--strict` for the same workspace.");
    expect(compat).toContain("**Generated bytes.**");
    expect(compat).toContain("comes in a minor release");
    const since: Record<number, string> = { 1: "every release", 2: "0.7.0", 3: "0.27.0", 4: "0.28.0", 5: "0.36.0", 6: "0.39.0", 7: "0.40.0", 8: "0.45.0", 9: "0.47.0", 10: "0.51.0", 11: "0.53.0", 12: "0.55.0", 13: "0.57.0", 14: "0.59.0", 15: "1.1.0", 16: "1.2.0", 17: "1.3.0" };
    const rows = compat.split("\n").filter((l) => /^\| `\d+` \|/.test(l));
    expect(rows).toHaveLength(17);
    for (const [n, v] of Object.entries(since)) {
      const row = rows.find((l) => l.startsWith(`| \`${n}\` |`));
      expect(row, `schema ${n}`).toBeDefined();
      expect(row!.endsWith(`| ${v} |`), `schema ${n} reads since ${v}`).toBe(true);
    }
  });

  it("Upgrading opens with to 1.3.0", () => {
    const upgradingStart = README.indexOf("## Upgrading");
    const afterUpgrading = README.slice(upgradingStart);
    const firstTo = afterUpgrading.split("\n").find((l) => l.startsWith("### to "));
    expect(firstTo).toBe("### to 1.3.0");
    expect(README).toContain("- **Nothing changes**: no generated byte, lock, Forge schema, `--json` key, command, flag or exit code.");
  });

  it("the roadmap says 1.0.0 closes the three phases, Later unchanged", () => {
    expect(README).toContain("craftar 1.0.0 closes phases 0, 1 and 2; *Later* is what comes next.");
  });
});
