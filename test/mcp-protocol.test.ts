import { afterEach, describe, expect, it } from "vitest";
import { profile, recipe, rule, scenario } from "./helpers/forge.js";
import { session } from "./helpers/mcp.js";
import { INSTRUCTIONS, PROTOCOL_VERSION, TOOL_NAMES, handleLine, launchRefusal, pinOf, type McpContext } from "../src/core/mcp-protocol.js";
import { readWorkspaceConfig } from "../src/core/sync.js";

// Spec 35 §4.3, §4.4, §4.7 — the method table. No tool runs here (test/mcp-tools.test.ts).

const cleanups: Array<() => Promise<unknown>> = [];
afterEach(async () => {
  while (cleanups.length) await cleanups.pop()!();
});
async function ws() {
  const s = await scenario({ ingredients: [rule("keep", "# Keep\n")], recipes: [recipe("base", ["rule/keep"])], profiles: [profile("acme", ["base"])] }, { config: { profile: "acme" } });
  cleanups.push(s.cleanup);
  return s;
}
async function fresh(over: Partial<McpContext> = {}) {
  const s = await ws();
  const ctx: McpContext = { root: s.wsRoot, fetch: false, home: process.env.CRAFTAR_HOME!, version: "9.9.9", registryOff: false, env: {}, pin: pinOf(await readWorkspaceConfig(s.wsRoot)), ...over };
  const state = { initialized: false };
  const send = async (m: unknown) => {
    const out = await handleLine(typeof m === "string" ? m : JSON.stringify(m), ctx, state);
    return out === null ? null : JSON.parse(out);
  };
  return { s, send, state };
}

describe("craftar mcp — the protocol table", () => {
  it("initialize answers 2025-06-18 to that revision and to any other, with exactly the tools capability", async () => {
    const { send } = await fresh();
    const want = { protocolVersion: "2025-06-18", capabilities: { tools: {} }, serverInfo: { name: "craftar", version: "9.9.9" }, instructions: INSTRUCTIONS };
    expect(PROTOCOL_VERSION).toBe("2025-06-18");
    expect(await send({ jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: "2025-06-18" } })).toEqual({ jsonrpc: "2.0", id: 1, result: want });
    expect(await send({ jsonrpc: "2.0", id: "b", method: "initialize", params: { protocolVersion: "2024-11-05" } })).toEqual({ jsonrpc: "2.0", id: "b", result: want });
    expect(await send({ jsonrpc: "2.0", id: 3, method: "initialize", params: { protocolVersion: "2099-01-01" } })).toEqual({ jsonrpc: "2.0", id: 3, result: want });
  });

  it("the instructions are the fixed paragraph, with no workspace data", () => {
    expect(INSTRUCTIONS).toBe(
      "This workspace's AI-coder files (`.claude/`, `.kiro/`, `AGENTS.md`) are generated by Craftar from a shared Forge. Do not edit a generated file by hand: the edit is flagged as drift and the file stops receiving updates until a person resolves it. Use `status` to see what is pending, `explain` to see where a file comes from, and tell the user to run `craftar sync` — these tools read only.",
    );
  });

  it("before initialize: ping answers {}, any other request is -32600, a notification produces nothing", async () => {
    const { send, state } = await fresh();
    expect(await send({ jsonrpc: "2.0", id: 1, method: "ping" })).toEqual({ jsonrpc: "2.0", id: 1, result: {} });
    expect(await send({ jsonrpc: "2.0", id: 2, method: "tools/list" })).toEqual({ jsonrpc: "2.0", id: 2, error: { code: -32600, message: "not initialized" } });
    expect(await send({ jsonrpc: "2.0", id: 3, method: "tools/call", params: { name: "status" } })).toEqual({ jsonrpc: "2.0", id: 3, error: { code: -32600, message: "not initialized" } });
    expect(await send({ jsonrpc: "2.0", method: "notifications/initialized" })).toBeNull();
    expect(await send({ jsonrpc: "2.0", method: "notifications/cancelled", params: { requestId: 3 } })).toBeNull();
    expect(await send({ jsonrpc: "2.0", method: "notifications/acme-unknown" })).toBeNull();
    expect(state.initialized).toBe(false);
  });

  it("tools/list: the seven names in order, read-only annotations, no outputSchema, cursor ignored", async () => {
    const s = await ws();
    const { request } = await session(s.wsRoot);
    const a = await request("tools/list");
    const b = await request("tools/list", { cursor: "anything" });
    expect(b.result).toEqual(a.result);
    expect(Object.keys(a.result)).toEqual(["tools"]);
    expect(a.result.tools.map((t: any) => t.name)).toEqual(["status", "diff", "explain", "recipes", "ingredients", "targets", "doctor"]);
    expect([...TOOL_NAMES]).toEqual(["status", "diff", "explain", "recipes", "ingredients", "targets", "doctor"]);
    for (const t of a.result.tools) {
      expect(Object.keys(t)).toEqual(["name", "title", "description", "inputSchema", "annotations"]);
      expect(t.annotations).toEqual({ readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: false });
      expect(t.inputSchema.type).toBe("object");
      expect(t.inputSchema.additionalProperties).toBe(false);
    }
    const schema = (n: string) => a.result.tools.find((t: any) => t.name === n).inputSchema;
    expect(Object.keys(schema("status").properties)).toEqual([]);
    expect(Object.keys(schema("diff").properties)).toEqual(["path"]);
    expect(schema("diff").required).toBeUndefined();
    expect(schema("explain").required).toEqual(["path"]);
    expect(Object.keys(schema("ingredients").properties)).toEqual(["recipe", "type"]);
  });

  it("the open-world hint follows --fetch", async () => {
    const s = await ws();
    const { request } = await session(s.wsRoot, { fetch: true });
    expect((await request("tools/list")).result.tools.map((t: any) => t.annotations.openWorldHint)).toEqual([true, true, true, true, true, true, true]);
  });

  it("an unknown method is -32601; a second initialize is answered and nothing is reset", async () => {
    const s = await ws();
    const { request, state, ctx } = await session(s.wsRoot);
    expect(await request("resources/list")).toEqual({ jsonrpc: "2.0", id: 2, error: { code: -32601, message: "Method not found" } });
    const pin = { ...ctx.pin };
    expect((await request("initialize", { protocolVersion: "2025-06-18" })).result.protocolVersion).toBe("2025-06-18");
    expect(state.initialized).toBe(true);
    expect(ctx.pin).toEqual(pin);
  });

  it("what has no id to answer produces no line, and the next line is still answered", async () => {
    const { send } = await fresh();
    // The 2025-06-18 schema types an error's id as string | number: an error with id null is not a valid message.
    expect(await send("{ not json")).toBeNull();
    expect(await send("")).toBeNull();
    expect(await send([{ jsonrpc: "2.0", id: 1, method: "ping" }])).toBeNull();
    expect(await send("7")).toBeNull();
    expect(await send({ jsonrpc: "2.0" })).toBeNull();
    expect(await send({ jsonrpc: "2.0", id: null, method: "ping" })).toBeNull();
    expect(await send({ jsonrpc: "2.0", id: { a: 1 }, method: "ping" })).toBeNull();
    expect(await send({ jsonrpc: "2.0", id: 5, result: {} })).toBeNull();
    expect(await send({ jsonrpc: "2.0", id: 6, error: { code: 1, message: "x" } })).toBeNull();
    expect(await send({ jsonrpc: "2.0", id: 7 })).toEqual({ jsonrpc: "2.0", id: 7, error: { code: -32600, message: "Invalid Request" } });
    expect(await send({ jsonrpc: "2.0", id: 8, method: 3 })).toEqual({ jsonrpc: "2.0", id: 8, error: { code: -32600, message: "Invalid Request" } });
    expect(await send({ jsonrpc: "2.0", id: 9, method: "ping" })).toEqual({ jsonrpc: "2.0", id: 9, result: {} });
  });

  it("tools/call: an unknown tool and invalid arguments are -32602, naming the key and never the value", async () => {
    const s = await ws();
    const { tool, request } = await session(s.wsRoot);
    const unknown = { code: -32602, message: "unknown tool — one of status, diff, explain, recipes, ingredients, targets, doctor" };
    expect((await tool("sync")).rpcError).toEqual(unknown);
    expect((await tool("SENTINEL-TOOL")).rpcError).toEqual(unknown);
    expect((await request("tools/call", {})).error).toEqual(unknown);
    expect((await request("tools/call", { name: 7 })).error).toEqual(unknown);
    expect((await tool("explain", {})).rpcError).toEqual({ code: -32602, message: "invalid arguments for explain: path: Required" });
    expect((await tool("explain")).rpcError).toEqual({ code: -32602, message: "invalid arguments for explain: path: Required" });
    expect((await tool("explain", { path: 7 })).rpcError).toEqual({ code: -32602, message: "invalid arguments for explain: path: Expected string, received number" });
    expect((await tool("diff", { path: "a", dir: "SENTINEL-VALUE" })).rpcError).toEqual({ code: -32602, message: "invalid arguments for diff: top level: Unrecognized key(s) in object: 'dir'" });
    expect((await tool("status", { workspace: "/SENTINEL" })).rpcError).toEqual({ code: -32602, message: "invalid arguments for status: top level: Unrecognized key(s) in object: 'workspace'" });
    expect((await tool("ingredients", { type: 3 })).rpcError).toEqual({ code: -32602, message: "invalid arguments for ingredients: type: Expected string, received number" });
    expect((await request("tools/call", { name: "diff", arguments: "SENTINEL" })).error).toEqual({ code: -32602, message: "invalid arguments for diff: top level: Expected object, received string" });
  });
});

describe("craftar mcp — the launch decision", () => {
  it("refuses a terminal first, then a directory with no craftar.yaml", () => {
    const tty = "craftar mcp speaks the Model Context Protocol on stdin and stdout — it is started by an AI coder, not typed; see the README";
    expect(launchRefusal(true, true, "/w")).toBe(tty);
    expect(launchRefusal(true, false, "/w")).toBe(tty);
    expect(launchRefusal(false, false, "/w")).toBe("no craftar.yaml in /w — craftar mcp serves one workspace; start it in one, or pass --workspace");
    expect(launchRefusal(false, true, "/w")).toBeNull();
  });
});
