/**
 * Spec 61 slice 3: the `gemini` target (§3.2; gate G2 ruled 2026-11-07, "Schema 17 + lock 6").
 * - A Forge file naming `gemini` needs `schema: 17` (near miss below it); the lock is written at 6 exactly when it names `gemini`.
 * - `GEMINI.md`: with `agents-md` among the targets it imports `AGENTS.md` and every rule with the default targets is left to it;
 *   otherwise the always-on rules are embedded and a scoped rule is listed at claude-code's / kiro's file or embedded.
 * - `.gemini/agents/<name>.md`, `.gemini/commands/<name>.toml`; skills through agent-skills; MCP and hooks not written (shared
 *   `.gemini/settings.json`).
 */
import { afterEach, describe, expect, it } from "vitest";
import { promises as fs } from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { parse as parseToml } from "smol-toml";
import { loadForge } from "../src/core/forge.js";
import { loadWorkspace, plan, apply, readLock, status } from "../src/core/sync.js";
import { carriedFile } from "../src/core/report.js";
import { profile, recipe, scenario, tmpDir, writeFiles, type IngredientSpec } from "./helpers/forge.js";
import { atLeastWin32 } from "./helpers/timeouts.js";

type Scenario = Awaited<ReturnType<typeof scenario>>;

const cleanups: Array<() => Promise<unknown>> = [];
afterEach(async () => {
  while (cleanups.length) await cleanups.pop()!();
});

async function ws(schema: number, targets: string[], ingredients: IngredientSpec[]): Promise<Scenario> {
  const refs = ingredients.map((i) => `${i.meta.type}/${i.meta.name}`);
  const s = await scenario({ ingredients, recipes: [recipe("base", refs)], profiles: [profile("acme", ["base"], targets)] }, { config: { profile: "acme" } });
  cleanups.push(s.cleanup);
  await fs.writeFile(path.join(s.forgeRoot, "craftar.forge.yaml"), YAML.stringify({ name: "test-forge", schema }));
  return s;
}
const load = (s: Scenario) => loadWorkspace(s.wsRoot, { home: process.env.CRAFTAR_HOME });
const planOf = async (s: Scenario) => plan(await load(s));
const syncOf = async (s: Scenario) => {
  const w = await load(s);
  const p = await plan(w);
  return apply(w, p, await status(w, p, await readLock(w.root)), {});
};
const text = (p: Awaited<ReturnType<typeof plan>>, rel: string) => p.files.find((f) => f.path === rel)!.content.toString("utf8");

const rule = (name: string, meta: Record<string, unknown> = {}, body = `${name} body.\n`): IngredientSpec => ({ meta: { type: "rule", name, ...meta }, files: { "rule.md": body } });
const HEADER = "<!-- GENERATED by craftar from the Forge. Edit the rule ingredients, not this file. -->\n\n";

describe("the gate: Forge schema 17, lock schema 6 (G2)", () => {
  it("schema 16 naming gemini → the near miss names schema 17; at 17 it loads; a workspace naming it writes lock 6, one naming codex stays 5", { timeout: atLeastWin32(60_000) }, async () => {
    const low = await ws(16, ["claude-code"], [rule("style", { targets: ["gemini"] })]);
    await expect(loadForge(low.forgeRoot)).rejects.toThrow("ingredients/rules/style/ingredient.yaml: targets: gemini needs schema: 17 in craftar.forge.yaml");
    expect((await syncOf(await ws(17, ["claude-code", "gemini"], [rule("style")]))).lock.schema).toBe(6);
    expect((await syncOf(await ws(17, ["claude-code", "codex"], [rule("style")]))).lock.schema).toBe(5);
  });

  it("a section marked targets=gemini below 17 is a near miss naming 17", async () => {
    const marked: IngredientSpec = { meta: { type: "rule", name: "tone" }, files: { "rule.md": "<!-- craftar:section intro targets=gemini -->\nHi.\n<!-- /craftar:section -->\n" } };
    await expect(planOf(await ws(16, ["claude-code"], [marked]))).rejects.toThrow("section intro targets=: gemini needs schema: 17 in craftar.forge.yaml");
  });

  it("a lock read as 5 refuses gemini; read as 6 it holds it", async () => {
    const dir = await tmpDir();
    cleanups.push(() => fs.rm(dir, { recursive: true, force: true }));
    const base = { forge: { source: ".", ref: null, commit: null }, profile: "acme", recipes: [], generatedAt: "x" };
    await writeFiles(dir, { "craftar.lock": JSON.stringify({ schema: 5, ...base, targets: ["gemini"], files: [] }) });
    await expect(readLock(dir)).rejects.toThrow(/not a valid lock/);
    await writeFiles(dir, { "craftar.lock": JSON.stringify({ schema: 6, ...base, targets: ["gemini"], files: [] }) });
    await expect(readLock(dir)).resolves.toMatchObject({ schema: 6 });
  });
});

describe("GEMINI.md", () => {
  it("with agents-md: an @AGENTS.md import, every default-targets rule left to AGENTS.md, a rule listed for gemini embedded", async () => {
    const p = await planOf(await ws(17, ["agents-md", "gemini"], [
      rule("style"),
      rule("api", { inclusion: "fileMatch", fileMatchPattern: "src/**" }),
      rule("only", { targets: ["gemini"] }),
    ]));
    expect(text(p, "GEMINI.md")).toBe(HEADER + "@AGENTS.md\n\n<!-- rule: only -->\nonly body.\n");
    expect(text(p, "AGENTS.md")).toContain("style body.");
    expect(p.files.find((f) => f.path === "GEMINI.md")!.ingredient).toBe("rule/*");
  });

  it("without agents-md: always-on rules embedded; a scoped rule listed at claude-code's file, or embedded with its scope", async () => {
    const withCc = await planOf(await ws(17, ["claude-code", "gemini"], [rule("style"), rule("api", { inclusion: "fileMatch", fileMatchPattern: "src/**" })]));
    expect(text(withCc, "GEMINI.md")).toBe(HEADER + "<!-- rule: style -->\nstyle body.\n\n## Scoped rules\n\n- `.claude/rules/api.md` — applies to `src/**`\n");
    const alone = await planOf(await ws(17, ["gemini"], [rule("api", { inclusion: "manual" })]));
    expect(text(alone, "GEMINI.md")).toBe(HEADER + "## Scoped rules\n\n<!-- rule: api -->\n> Scoped rule — manual\n\napi body.\n");
  });

  it("a .claude/rules/ reference names claude-code's file or the rule's place in AGENTS.md (Gemini names no rule file of its own)", async () => {
    const p = await planOf(await ws(17, ["agents-md", "gemini"], [rule("only", { targets: ["gemini"] }, "See .claude/rules/style.md.\n"), rule("style")]));
    expect(text(p, "GEMINI.md")).toContain("See AGENTS.md (rule: style).");
  });

  it("review: in a gemini-only workspace a reference to a rule GEMINI.md holds names its place there, as a token and as a link", async () => {
    const p = await planOf(await ws(17, ["gemini"], [
      rule("only", {}, "See .claude/rules/style.md and [the style](.claude/rules/style.md).\n"),
      rule("style"),
    ]));
    const t = text(p, "GEMINI.md");
    expect(t).toContain("See GEMINI.md (rule: style) and [the style](GEMINI.md).");
    expect(t).not.toContain("rule not in this workspace");
    expect(p.warnings.filter((w) => w.startsWith("gemini:"))).toEqual([]);
  });

  it("review: the rules index in GEMINI.md names a rule's place there; a placeholder not alone on its line is the misplaced warning", async () => {
    const indexed = await planOf(await ws(17, ["gemini"], [rule("idx", {}, "Rules:\n{{craftar.rules.index}}\n"), rule("style", { description: "Style" })]));
    expect(text(indexed, "GEMINI.md")).toContain("GEMINI.md (rule: style)");
    expect(text(indexed, "GEMINI.md")).not.toContain("`GEMINI.md (rule: style)`");
    const misplaced = await planOf(await ws(17, ["gemini"], [rule("idx", {}, "Rules: {{craftar.rules.index}} here.\n")]));
    expect(misplaced.warnings.some((w) => w.startsWith("{{craftar.rules.index}} must stand alone on its line — left as written in GEMINI.md:"))).toBe(true);
    expect(misplaced.warnings.some((w) => w.includes("expanded in rule and steering bodies only"))).toBe(false);
  });

  it("keeps the line endings of the file it replaces and never writes a BOM", { timeout: atLeastWin32(30_000) }, async () => {
    const s = await ws(17, ["gemini"], [rule("style")]);
    await syncOf(s);
    const file = path.join(s.wsRoot, "GEMINI.md");
    const lf = await fs.readFile(file, "utf8");
    await fs.writeFile(file, "﻿" + lf.replace(/\n/g, "\r\n"));
    expect(text(await planOf(s), "GEMINI.md")).toBe(lf.replace(/\n/g, "\r\n"));
  });
});

describe("agents and commands", () => {
  it(".gemini/agents/<name>.md: name, description, model inherit unless a Gemini model; tools dropped and warned", async () => {
    const p = await planOf(await ws(17, ["gemini"], [
      { meta: { type: "agent", name: "fast", description: "Quick", model: "gemini-2.5-flash" }, files: { "agent.md": "Be quick.\n" } },
      { meta: { type: "agent", name: "helper", description: "Helps", model: "sonnet", tools: ["Read"] }, files: { "agent.md": "Help.\n" } },
    ]));
    expect(text(p, ".gemini/agents/fast.md")).toBe('---\nname: "fast"\ndescription: "Quick"\nmodel: "gemini-2.5-flash"\n---\nBe quick.\n');
    expect(text(p, ".gemini/agents/helper.md")).toBe('---\nname: "helper"\ndescription: "Helps"\nmodel: inherit\n---\nHelp.\n');
    expect(p.warnings).toContain('gemini: agent "helper": model is not a Gemini model; inherit written');
    expect(p.warnings).toContain('gemini: agent "helper": tools are not written (Gemini\'s tool names differ); dropped');
  });

  it(".gemini/commands/<name>.toml: description and prompt, $ARGUMENTS as {{args}}; argument-hint dropped and warned", async () => {
    const p = await planOf(await ws(17, ["gemini"], [
      { meta: { type: "command", name: "review", description: "Review", argumentHint: "<file>" }, files: { "command.md": "Review $ARGUMENTS now.\n" } },
    ]));
    const t = text(p, ".gemini/commands/review.toml");
    expect(t).toBe('description = "Review"\nprompt = """\nReview {{args}} now.\n"""\n');
    expect(parseToml(t)).toEqual({ description: "Review", prompt: "Review {{args}} now.\n" });
    expect(p.warnings).toContain('gemini: command "review": argument-hint has no Gemini field; dropped');
  });

  it("with agent-skills, a default-targets command is left to .agents/skills/ (explain names it); one listed for gemini keeps its file", async () => {
    const p = await planOf(await ws(17, ["gemini", "agent-skills"], [
      { meta: { type: "command", name: "review", description: "Review" }, files: { "command.md": "Review.\n" } },
      { meta: { type: "command", name: "fix", description: "Fix", targets: ["gemini", "agent-skills"] }, files: { "command.md": "Fix.\n" } },
    ]));
    const paths = p.files.map((f) => f.path);
    expect(paths).not.toContain(".gemini/commands/review.toml");
    expect(paths).toContain(".gemini/commands/fix.toml");
    expect(carriedFile(p, ".gemini/commands/review.toml")).toEqual({ path: ".gemini/commands/review.toml", writtenTo: ".agents/skills/review/SKILL.md", ingredient: "command/review" });
  });

  it("a skill warns only without agent-skills; an MCP server and a hook are not written, each warned", async () => {
    const skill: IngredientSpec = { meta: { type: "skill", name: "docs", layout: "dir" }, files: { "SKILL.md": "---\nname: docs\ndescription: Docs\n---\nDocs.\n" } };
    const mcp: IngredientSpec = { meta: { type: "mcp", name: "tracker", server: { command: "npx", args: ["t"] } } };
    const hook: IngredientSpec = { meta: { type: "hook", name: "h", files: ["h.sh"], registration: [{ event: "Stop", command: "./h.sh" }] }, files: { "h.sh": "#!/bin/sh\n" } };
    const alone = await planOf(await ws(17, ["gemini"], [skill, mcp, hook]));
    expect(alone.warnings).toContain("gemini: 1 skill ingredient(s) have no Gemini equivalent — skipped: skill/docs");
    expect(alone.warnings).toContain("gemini: 1 mcp ingredient(s) have no Gemini equivalent — skipped: mcp/tracker");
    expect(alone.warnings).toContain("gemini: 1 hook ingredient(s) have no Gemini equivalent — skipped: hook/h");
    expect(alone.files.some((f) => f.path.startsWith(".gemini/settings"))).toBe(false);
    const carried = await planOf(await ws(17, ["gemini", "agent-skills"], [skill]));
    expect(carried.warnings.filter((w) => w.startsWith("gemini:"))).toEqual([]);
  });
});
