/**
 * CLI tests for `craftar services` commands (spec 31 step 31e).
 * 
 * These tests use PATH manipulation to avoid requiring Docker to be installed.
 * No Docker stub is used - we simply remove docker from PATH to test error handling.
 */
import { describe, it, expect, beforeEach, afterEach } from "vitest";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { runCli } from "./helpers/cli.js";
import { hashNormalized } from "../src/core/text.js";

describe("craftar services CLI", () => {
  let tmpDir: string;

  beforeEach(async () => {
    tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), "craftar-services-cli-"));
  });

  afterEach(async () => {
    await fs.rm(tmpDir, { recursive: true, force: true });
  });

  /** Create a minimal workspace with craftar.yaml and lock. */
  async function createWorkspace(opts: { withServices?: boolean } = {}): Promise<string> {
    const wsRoot = path.join(tmpDir, "workspace");
    const forgeRoot = path.join(tmpDir, "forge");

    // Create Forge
    await fs.mkdir(forgeRoot, { recursive: true });
    await fs.writeFile(path.join(forgeRoot, "craftar.forge.yaml"), "name: test-forge\n");
    await fs.mkdir(path.join(forgeRoot, "profiles/test"), { recursive: true });
    await fs.writeFile(path.join(forgeRoot, "profiles/test/profile.yaml"), "name: test\nrecipes: [base]\ntargets: [claude-code]\n");
    await fs.mkdir(path.join(forgeRoot, "recipes"), { recursive: true });
    await fs.writeFile(path.join(forgeRoot, "recipes/base.yaml"), "name: base\ningredients: []\n");

    // Create workspace
    await fs.mkdir(wsRoot, { recursive: true });
    await fs.writeFile(path.join(wsRoot, "craftar.yaml"), `forge: ../forge\nprofile: test\n`);

    // Create lock
    const lockFiles: Array<{ path: string; hash: string; target: string; ingredient: string }> = [];

    if (opts.withServices) {
      // Create service files
      const stackContent = "# Generated by craftar\ninclude:\n  - path: services/echo/compose.yaml\n";
      const fragmentContent = "services:\n  echo:\n    image: alpine\n";
      const gitattributes = "* -text\n";

      await fs.mkdir(path.join(wsRoot, ".craftar/services/echo"), { recursive: true });
      await fs.writeFile(path.join(wsRoot, ".craftar/compose.yaml"), stackContent);
      await fs.writeFile(path.join(wsRoot, ".craftar/services/echo/compose.yaml"), fragmentContent);
      await fs.writeFile(path.join(wsRoot, ".craftar/.gitattributes"), gitattributes);

      lockFiles.push(
        { path: ".craftar/compose.yaml", hash: hashNormalized(Buffer.from(stackContent)), target: "services", ingredient: "service/*" },
        { path: ".craftar/services/echo/compose.yaml", hash: hashNormalized(Buffer.from(fragmentContent)), target: "services", ingredient: "service/echo" },
        { path: ".craftar/.gitattributes", hash: hashNormalized(Buffer.from(gitattributes)), target: "services", ingredient: "service/*" },
      );
    }

    const lock = {
      schema: 3,
      forge: { source: "../forge", ref: null, commit: null },
      profile: "test",
      recipes: ["base"],
      targets: ["claude-code"],
      generatedAt: new Date().toISOString(),
      files: lockFiles,
    };
    await fs.writeFile(path.join(wsRoot, "craftar.lock"), JSON.stringify(lock, null, 2));

    return wsRoot;
  }

  /** Get an empty PATH that excludes docker. */
  function emptyPath(): NodeJS.ProcessEnv {
    // Set PATH to something minimal that won't include docker
    return { PATH: "/nonexistent" };
  }

  describe("services up", () => {
    it("fails with 'Docker is not installed' when docker is not in PATH", async () => {
      const wsRoot = await createWorkspace({ withServices: true });
      const result = runCli(["services", "up", "--workspace", wsRoot], { env: emptyPath() });

      expect(result.code).toBe(1);
      expect(result.stderr).toContain("Docker is not installed");
    });

    it("fails with 'no craftar.lock' when lock is missing", async () => {
      const wsRoot = await createWorkspace();
      await fs.unlink(path.join(wsRoot, "craftar.lock"));

      const result = runCli(["services", "up", "--workspace", wsRoot], { env: emptyPath() });

      expect(result.code).toBe(1);
      expect(result.stderr).toContain("no craftar.lock");
    });

    it("fails with 'no services recorded' when lock has no service entries", async () => {
      const wsRoot = await createWorkspace({ withServices: false });

      // With a valid docker, it would fail because no services are recorded
      // Since we don't have docker, it fails earlier with "Docker is not installed"
      const result = runCli(["services", "up", "--workspace", wsRoot], { env: emptyPath() });

      // The error is about Docker, not services, because Docker check comes first
      expect(result.code).toBe(1);
      expect(result.stderr).toContain("Docker is not installed");
    });
  });

  describe("services down", () => {
    it("fails with 'Docker is not installed' when docker is not in PATH", async () => {
      const wsRoot = await createWorkspace({ withServices: true });
      const result = runCli(["services", "down", "--workspace", wsRoot], { env: emptyPath() });

      expect(result.code).toBe(1);
      expect(result.stderr).toContain("Docker is not installed");
    });

    it("supports --volumes flag", async () => {
      const wsRoot = await createWorkspace({ withServices: true });
      const result = runCli(["services", "down", "--volumes", "--workspace", wsRoot], { env: emptyPath() });

      // Still fails because no docker, but the flag is accepted
      expect(result.code).toBe(1);
      expect(result.stderr).toContain("Docker is not installed");
    });
  });

  describe("services status", () => {
    it("fails with 'Docker is not installed' when docker is not in PATH", async () => {
      const wsRoot = await createWorkspace({ withServices: true });
      const result = runCli(["services", "status", "--workspace", wsRoot], { env: emptyPath() });

      expect(result.code).toBe(1);
      expect(result.stderr).toContain("Docker is not installed");
    });

    it("supports --json flag", async () => {
      const wsRoot = await createWorkspace({ withServices: true });
      const result = runCli(["services", "status", "--json", "--workspace", wsRoot], { env: emptyPath() });

      // Still fails because no docker, but the flag is accepted
      expect(result.code).toBe(1);
      expect(result.stderr).toContain("Docker is not installed");
    });
  });

  describe("help text", () => {
    it("shows services subcommands in help", () => {
      const result = runCli(["services", "--help"]);

      expect(result.code).toBe(0);
      expect(result.stdout).toContain("up");
      expect(result.stdout).toContain("down");
      expect(result.stdout).toContain("status");
      expect(result.stdout).toContain("local services");
    });

    it("shows services up help", () => {
      const result = runCli(["services", "up", "--help"]);

      expect(result.code).toBe(0);
      expect(result.stdout).toContain("--workspace");
      expect(result.stdout).toContain("--wait");
    });

    it("shows services down help", () => {
      const result = runCli(["services", "down", "--help"]);

      expect(result.code).toBe(0);
      expect(result.stdout).toContain("--workspace");
      expect(result.stdout).toContain("--volumes");
    });

    it("shows services status help", () => {
      const result = runCli(["services", "status", "--help"]);

      expect(result.code).toBe(0);
      expect(result.stdout).toContain("--workspace");
      expect(result.stdout).toContain("--json");
    });
  });
});

describe("craftar targets — service line", () => {
  it("text output includes services line in paths section", () => {
    const result = runCli(["targets"]);

    expect(result.code).toBe(0);
    expect(result.stdout).toContain("services");
    expect(result.stdout).toContain(".craftar/compose.yaml");
  });

  it("--json output includes services object", () => {
    const result = runCli(["targets", "--json"]);

    expect(result.code).toBe(0);
    const json = JSON.parse(result.stdout);
    expect(json.services).toBeDefined();
    expect(json.services.output).toContain(".craftar/compose.yaml");
    expect(json.services.output).toContain(".craftar/services/<name>/compose.yaml");
  });
});
