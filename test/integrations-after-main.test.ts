import { afterEach, describe, expect, it } from "vitest";
import { promises as fs } from "node:fs";
import path from "node:path";
import { runCli } from "./helpers/cli.js";
import { profile, recipe, rule, type ForgeSpec } from "./helpers/forge.js";
import { ado, forgeAt, mcp, PM, snapshot, sync, STORIES } from "./helpers/integrations.js";

const cleanups: Array<() => Promise<unknown>> = [];
afterEach(async () => {
  while (cleanups.length) await cleanups.pop()!();
});

/** A Forge at `schema` and a workspace synced from it. */
async function synced(schema: number, spec: ForgeSpec, ws: { config: { profile: string; recipes?: { add?: string[]; remove?: string[] } } } = { config: { profile: "acme" } }) {
  const s = await forgeAt(schema, spec, ws);
  cleanups.push(s.cleanup);
  await sync(s.wsRoot);
  return s;
}

/** Forge files whose bytes moved (added, removed or changed), sorted. */
async function moved(forgeRoot: string, before: Record<string, string>): Promise<string[]> {
  const after = await snapshot(forgeRoot);
  return [...new Set([...Object.keys(before), ...Object.keys(after)])].filter((k) => before[k] !== after[k]).sort();
}

describe("--prefer-kiro on a rule the block provides", () => {
  const LEFT_TO_RECIPE_LINE = "  left to recipe pm-azure-devops (integrations.pm): rule/stories-azure-devops, mcp/azure-devops — not compared; when this workspace resolves that recipe, craftar status shows whether its copies differ";
  const WARN_LINE = "  warn --prefer-kiro stories-azure-devops: rule/stories-azure-devops is left to recipe pm-azure-devops (integrations.pm) — nothing to prefer; its steering file was not used";

  it("C1. --prefer-kiro on a rule the block provides — untouched workspace", async () => {
    const s = await synced(3, ado());
    const before = await snapshot(s.forgeRoot);
    const r = runCli(["import", "--from", "claude-code", "--forge", s.forgeRoot, "--profile", "acme", "--workspace", s.wsRoot, "--prefer-kiro", "stories-azure-devops"]);
    const forgeFiles = await moved(s.forgeRoot, before);
    const lines = r.stdout.split("\n");

    expect(r.code).toBe(0);
    expect(forgeFiles).toEqual([]);
    expect(lines).toContain(LEFT_TO_RECIPE_LINE);
    expect(lines).toContain(WARN_LINE);
    expect(lines.filter((l) => l.startsWith("  prefer-kiro"))).toEqual([]);
  });

  // Fail-first (before the fix, with the provided.has check disabled):
  // code: 1
  // stderr: error: import: --prefer-kiro stories-azure-devops: .kiro/steering/stories-azure-devops.md line 6 would not come back from the rule built from it — it names .claude/rules/ where sync writes .kiro/steering/; edit the steering file or drop stories-azure-devops from --prefer-kiro
  // The Forge was left untouched.
  it("C2. --prefer-kiro on a rule the block provides — steering that would refuse", async () => {
    const s = await synced(3, ado());
    // Overwrite the steering file with content that would not come back.
    // The rule cites .claude/rules/workflow.md but sync would write .kiro/steering/workflow.md.
    const steeringPath = path.join(s.wsRoot, ".kiro/steering/stories-azure-devops.md");
    await fs.writeFile(steeringPath, `---
inclusion: always
---
AUTOGENERATED

Stories live in Azure DevOps, see .claude/rules/workflow.md for the workflow.
`);
    const before = await snapshot(s.forgeRoot);
    const r = runCli(["import", "--from", "claude-code", "--forge", s.forgeRoot, "--profile", "acme", "--workspace", s.wsRoot, "--prefer-kiro", "stories-azure-devops"]);
    const forgeFiles = await moved(s.forgeRoot, before);
    const lines = r.stdout.split("\n");

    expect(r.code).toBe(0);
    expect(forgeFiles).toEqual([]);
    expect(lines).toContain(LEFT_TO_RECIPE_LINE);
    expect(lines).toContain(WARN_LINE);
    expect(lines.filter((l) => l.startsWith("  prefer-kiro"))).toEqual([]);
  });

  it("C3. (control) --prefer-kiro on a rule base lists", async () => {
    const s = await synced(3, ado());
    const r = runCli(["import", "--from", "claude-code", "--forge", s.forgeRoot, "--profile", "acme", "--workspace", s.wsRoot, "--prefer-kiro", "workflow"]);
    const lines = r.stdout.split("\n");

    expect(r.code).toBe(0);
    // Print once, then pin:
    expect(lines).toContain("  prefer-kiro rule/workflow — source .kiro/steering/workflow.md (7 lines; .claude/rules/workflow.md has 1)");
    expect(lines).toContain("  left to recipe pm-azure-devops (integrations.pm): rule/stories-azure-devops, mcp/azure-devops — not compared; when this workspace resolves that recipe, craftar status shows whether its copies differ");
    expect(lines.filter((l) => l.includes("warn --prefer-kiro workflow"))).toEqual([]);
  });

  it("C5. (control, below the gate) schema 2, the recipe listed by hand", async () => {
    // Schema 2, recipe listed by hand: ado({}, PM, { recipes: [...], params: {...} })
    const s = await synced(2, ado({}, PM, { recipes: ["base", "pm-azure-devops"], params: { "integrations.pm.org": "acme", "integrations.pm.project": "Platform" } }));
    const r = runCli(["import", "--from", "claude-code", "--forge", s.forgeRoot, "--profile", "acme", "--workspace", s.wsRoot, "--prefer-kiro", "stories-azure-devops"]);
    const lines = r.stdout.split("\n");

    expect(r.code).toBe(0);
    // Print once, then pin:
    expect(lines).toContain("  prefer-kiro rule/stories-azure-devops — source .kiro/steering/stories-azure-devops.md (7 lines; .claude/rules/stories-azure-devops.md has 1)");
    // No warning line holds "left to recipe":
    expect(lines.filter((l) => l.includes("left to recipe"))).toEqual([]);
  });

  it("C6. --prefer-kiro on an as: rule — the warn line names the Forge ref", async () => {
    // 33f case 13's Forge: rule("stories-azure-devops", STORIES, { as: "stories" })
    const spec: ForgeSpec = {
      ingredients: [
        rule("workflow", "# Workflow\n"),
        rule("where", "Org {{integrations.pm.org}}\n"),
        rule("stories-azure-devops", STORIES, { as: "stories" }),
        mcp("azure-devops", { command: "npx", args: ["-y", "ado-mcp"] }),
      ],
      recipes: [
        recipe("base", ["rule/workflow", "rule/where"]),
        recipe("pm-azure-devops", ["mcp/azure-devops", "rule/stories-azure-devops"], { slot: "pm" }),
      ],
      profiles: [profile("acme", ["base"], ["claude-code", "kiro"], { integrations: PM })],
    };
    const s = await synced(3, spec);
    const r = runCli(["import", "--from", "claude-code", "--forge", s.forgeRoot, "--profile", "acme", "--workspace", s.wsRoot, "--prefer-kiro", "stories"]);
    const lines = r.stdout.split("\n");

    expect(r.code).toBe(0);
    // The warn line names the Forge ref (rule/stories-azure-devops), not rule/stories:
    expect(lines).toContain("  warn --prefer-kiro stories: rule/stories-azure-devops is left to recipe pm-azure-devops (integrations.pm) — nothing to prefer; its steering file was not used");
    expect(lines.filter((l) => l.startsWith("  prefer-kiro"))).toEqual([]);
  });
});
