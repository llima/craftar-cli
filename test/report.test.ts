import { afterEach, describe, expect, it } from "vitest";
import { promises as fs } from "node:fs";
import path from "node:path";
import { eightStates, type Scenario } from "./helpers/states.js";
import { loadWorkspace, plan, readLock, status, type FileStatus } from "../src/core/sync.js";
import { EXAMPLE_CONTENT_HIDDEN, MCP_CONTENT_HIDDEN, explainSkip, notProduced, statusPath, statusReport } from "../src/core/report.js";

// Spec 35 §5.1 (and spec 36 §17): the builders the commands, the MCP server and the dashboard share — tested directly.

const cleanups: Array<() => Promise<unknown>> = [];
afterEach(async () => {
  while (cleanups.length) await cleanups.pop()!();
});
const kept = <T extends Scenario>(s: T): T => (cleanups.push(s.cleanup), s);
const HOME = { home: process.env.CRAFTAR_HOME };
async function loaded(s: Scenario) {
  const ws = await loadWorkspace(s.wsRoot, HOME);
  const p = await plan(ws);
  const lock = await readLock(ws.root);
  return { ws, p, lock, st: await status(ws, p, lock) };
}
const R = ".claude/rules";

describe("the small ones", () => {
  it("statusPath, notProduced, the two withheld-content sentences (no indentation), explainSkip", () => {
    expect([statusPath("a/b.md"), statusPath("./a/b.md"), statusPath(".\\a\\b.md"), statusPath("../a"), statusPath("/abs/a")]).toEqual(["a/b.md", "a/b.md", "a/b.md", "../a", "/abs/a"]);
    expect(notProduced("x.md", "acme")).toBe("x.md is not produced by the Forge for profile acme");
    expect(EXAMPLE_CONTENT_HIDDEN).toBe("content not shown: an example file may hold a value typed by hand");
    expect(MCP_CONTENT_HIDDEN).toBe("content not shown: an MCP configuration file may hold a value typed by hand");
    const skip = (state: FileStatus["state"]) => explainSkip({ path: "x", state });
    expect(skip("drift")).toBe("hand-edited since last sync — `craftar drift show <path>`, then `craftar drift discard` or `craftar drift promote`");
    expect(skip("collision")).toBe("exists but was never generated by craftar and differs from the Forge — rename it or import it");
    expect(skip("orphan-drift")).toBe("no longer produced by the Forge but hand-edited — kept; `craftar drift discard <path>` removes it, or delete it yourself");
    expect(skip("update")).toBe("");
  });
});

describe("statusReport", () => {
  it("is the status --json document: four keys, rows without `planned`, the plan's warnings, the unset keys", async () => {
    const { ws, p, lock, st } = await loaded(kept(await eightStates()));
    const r = statusReport(ws, p, lock, st);
    expect(Object.keys(r)).toEqual(["forge", "statuses", "warnings", "unsetParams"]);
    expect(r.forge).toEqual({ kind: "path", source: "../forge", ref: null, defaultBranch: null, commit: null, lockCommit: null, fetched: false });
    expect(Object.keys(r.forge)).toEqual(["kind", "source", "ref", "defaultBranch", "commit", "lockCommit", "fetched"]);
    expect(r.statuses).toHaveLength(8);
    for (const s of r.statuses) expect(Object.hasOwn(s, "planned")).toBe(false);
    expect(Object.keys(r.statuses[2])).toEqual(["path", "state", "target", "ingredient", "lock"]);
    expect(r.warnings).toBe(p.warnings);
    expect(r.unsetParams).toEqual([]);
    expect(st[7].planned).toBeDefined(); // the caller's rows are not touched
  });
});
