  it("test 14: full cycle through status/apply — new → unchanged; hand edit → drift, sync --check exits 1; removing recipe → orphan", async () => {
    const s = await scenario(forgeS, { config: { profile: "acme" } });
    cleanups.push(s.cleanup);

    // First sync: new → write
    let ws = await loadWorkspace(s.wsRoot);
    let p = await plan(ws);
    let st = await status(ws, p, null);
    // Assert non-empty before filtering with every()
    const newEntries = st.filter((e) => e.target === "services");
    expect(newEntries.length).toBe(4);
    expect(newEntries.every((e) => e.state === "new")).toBe(true);
    await apply(ws, p, st);

    // Verify lock entries have exactly the expected keys: path, hash, target, ingredient (no mode) - check raw JSON
    const lockJson = JSON.parse(await fs.readFile(path.join(s.wsRoot, "craftar.lock"), "utf8"));
    const craftarEntries = lockJson.files.filter((f: { path: string }) => f.path.startsWith(".craftar/"));
    expect(craftarEntries.length).toBe(4);
    for (const entry of craftarEntries) {
      expect(Object.keys(entry).sort()).toEqual(["hash", "ingredient", "path", "target"]);
      expect(entry.target).toBe("services");
    }

    // Second status: unchanged
    ws = await loadWorkspace(s.wsRoot);
    p = await plan(ws);
    st = await status(ws, p, await readLock(ws.root));
    const unchangedEntries = st.filter((e) => e.target === "services");
    expect(unchangedEntries.length).toBe(4);
    expect(unchangedEntries.every((e) => e.state === "unchanged")).toBe(true);

    // Hand edit → drift
    await fs.appendFile(path.join(s.wsRoot, ".craftar/services/echo/compose.yaml"), "# hand edit\n");
    st = await status(ws, p, await readLock(ws.root));
    const driftEntry = st.find((e) => e.path === ".craftar/services/echo/compose.yaml");
    expect(driftEntry?.state).toBe("drift");

    // sync --check exits 1
    const result = await runCli(["sync", "--check"], s.wsRoot);
    expect(result.code).toBe(1);

    // Removing the recipe → orphan, next sync deletes the four files (but orphan-drift is kept)
    await fs.writeFile(path.join(s.forgeRoot, "recipes/base.yaml"), YAML.stringify({ name: "base", ingredients: [] }));
    ws = await loadWorkspace(s.wsRoot);
    p = await plan(ws);
    st = await status(ws, p, await readLock(ws.root));
    const orphans = st.filter((e) => e.state === "orphan" || e.state === "orphan-drift");
    expect(orphans.length).toBe(4);

    // Sync with overwriteDrift: orphan-drift entries are KEPT, so the hand-edited file stays
    await apply(ws, p, st, { overwriteDrift: true });
    let lock = await readLock(s.wsRoot);
    // Lock is still schema 3 because orphan-drift entry is kept (spec 31 §5.2)
    expect(lock!.schema).toBe(3);

    // Delete the hand-edited file manually, then sync again → lock is schema 2
    await fs.rm(path.join(s.wsRoot, ".craftar/services/echo/compose.yaml"));
    ws = await loadWorkspace(s.wsRoot);
    p = await plan(ws);
    st = await status(ws, p, await readLock(ws.root));
    await apply(ws, p, st);
    lock = await readLock(s.wsRoot);
    expect(lock!.schema).toBe(2);
  });

