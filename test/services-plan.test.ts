// Service ingredient helper
const service = (
  name: string,
  compose: string,
  files: string[] = [],
  extra: Record<string, unknown> = {},
): IngredientSpec => ({
  meta: { type: "service", name, compose: "compose.yaml", files, ...extra },
  files: { "compose.yaml": compose, ...Object.fromEntries(files.map((f) => [f, ""])) },
});

// Forge S: service echo with fragment, init script, params
const echoFragment = `services:
  echo:
    image: example/echo:1
    ports: ["8080:80"]
    environment:
      GREETING: "{{greeting}}"
      TOKEN: \${ACME_TOKEN:-fake}
`;
const echoInitScript = "#!/bin/sh\r\necho {{greeting}}\r\n";

const forgeS: ForgeSpec = {
  ingredients: [
    {
      meta: {
        type: "service",
        name: "echo",
        compose: "compose.yaml",
        files: ["init/a.sh"],
        executable: ["init/a.sh"],
        params: { greeting: { default: "hello" } },
      },
      files: {
        "compose.yaml": echoFragment,
        "init/a.sh": echoInitScript,
      },
    },
  ],
  recipes: [recipe("base", ["service/echo"])],
  profiles: [profile("acme", ["base"], ["claude-code"])],
};

async function planned(f: ForgeSpec, w: { config: Record<string, unknown>; local?: Record<string, unknown> } = { config: { profile: "acme" } }) {
  const s = await scenario(f, w);
  cleanups.push(s.cleanup);
  const ws = await loadWorkspace(s.wsRoot);
  const p = await plan(ws);
  return { s, ws, p };
}

