import type { Ingredient } from "../schema/index.js";
import type { ResolvedIngredient } from "../core/resolve.js";
import { tomlDocument } from "../core/toml.js";
import { ruleMarker } from "./agents-md.js";
import { appliesTo, effectiveTargets, outName, ownRuleRefs, ruleFile, ruleWriter, textFile } from "./shared.js";
import type { Emitter, PlannedFile } from "./types.js";

/** Gemini's rules file (spec 61 slice 3, §3.2): the workspace's `GEMINI.md`, read by Gemini CLI; it takes `@file` imports. */
export const GEMINI_MD = "GEMINI.md";

/**
 * Gemini CLI target (spec 61 §3.2, slice 3; its gate G2, Forge schema 17 and lock schema 6): `GEMINI.md`,
 * `.gemini/agents/<name>.md`, `.gemini/commands/<name>.toml`. With `agents-md` among the targets `GEMINI.md` imports `AGENTS.md`
 * (`@AGENTS.md`) — Gemini reads `AGENTS.md` only through `context.fileName`, in the shared `.gemini/settings.json` — and every rule
 * with the default targets is left to it (the `CARRIED` table), so nothing is written twice. Skills reach Gemini through the
 * agent-skills target (the `.agents/skills/` alias); its MCP servers and hooks live in the shared `.gemini/settings.json` and are not
 * written (D5, H1) — the matrix warns for each here. Text keeps the line endings of the file it replaces (LF when new), no BOM.
 */
export const gemini: Emitter<"gemini"> = {
  target: "gemini",
  async emit(ctx) {
    const out: PlannedFile[] = [];
    const t = "gemini";
    const refs = ownRuleRefs(ctx, t);
    const rules: ResolvedIngredient[] = [];
    for (const ing of ctx.aimed) {
      const m = ctx.meta(ing);
      switch (m.type) {
        case "rule":
          rules.push(ing); // collected into GEMINI.md below
          break;
        case "agent": {
          const name = outName(m);
          const lines = [`name: ${JSON.stringify(name)}`];
          if (m.description) lines.push(`description: ${JSON.stringify(m.description)}`);
          else ctx.warn(`gemini: agent "${name}" has no description, which Gemini requires`);
          const geminiModel = m.model !== undefined && /^gemini/.test(m.model);
          if (m.model && !geminiModel) ctx.warn(`gemini: agent "${name}": model is not a Gemini model; inherit written`);
          lines.push(`model: ${geminiModel ? JSON.stringify(m.model) : "inherit"}`);
          if ((m.tools?.length ?? 0) > 0) ctx.warn(`gemini: agent "${name}": tools are not written (Gemini's tool names differ); dropped`);
          const doc = `---\n${lines.join("\n")}\n---\n` + refs.resolve(await ctx.text(ing, m.file, t), ing.ref);
          out.push(await textFile(ctx, `.gemini/agents/${name}.md`, doc, t, ing.ref, { keepBom: false }));
          break;
        }
        case "command": {
          const name = outName(m);
          if (m.argumentHint) ctx.warn(`gemini: command "${name}": argument-hint has no Gemini field; dropped`);
          if (m.allowedTools) ctx.warn(`gemini: command "${name}": allowed-tools has no Gemini field; dropped`);
          const prompt = refs.resolve(await ctx.text(ing, m.file, t), ing.ref).replaceAll("$ARGUMENTS", "{{args}}");
          const entries: Array<readonly [string, string | { multiline: string }]> = [];
          if (m.description) entries.push(["description", m.description]);
          entries.push(["prompt", { multiline: prompt }]);
          out.push(await textFile(ctx, `.gemini/commands/${name}.toml`, tomlDocument(entries), t, ing.ref, { keepBom: false }));
          break;
        }
        default: {
          const never: never = m;
          throw new Error(`internal: ${t} has no case for ${(never as Ingredient).type}`);
        }
      }
    }

    // GEMINI.md: the import of AGENTS.md when agents-md writes one, then the rules aimed at gemini itself.
    const writesAgentsMd =
      ctx.resolution.targets.includes("agents-md") &&
      ctx.resolution.ingredients.some((i) => i.meta.type === "rule" && appliesTo(effectiveTargets(i.meta, ctx.resolution), "agents-md"));
    if (writesAgentsMd || rules.length) {
      const parts = ["<!-- GENERATED by craftar from the Forge. Edit the rule ingredients, not this file. -->", ""];
      if (writesAgentsMd) parts.push("@AGENTS.md", "");
      const scopedLines: string[] = [];
      const embedded: string[] = [];
      for (const ing of rules) {
        const m = ctx.meta(ing);
        if (m.type !== "rule") continue;
        const body = refs.index(refs.resolve(await ctx.text(ing, m.file, t), ing.ref), GEMINI_MD).replace(/\n+$/, "");
        if (m.inclusion === "always") {
          parts.push(ruleMarker(outName(m)), body, "");
          continue;
        }
        const scope = m.inclusion === "fileMatch" ? `applies to \`${[m.fileMatchPattern].flat().join("`, `")}\`` : m.inclusion;
        const writer = ruleWriter(ctx.resolution.targets, effectiveTargets(m, ctx.resolution));
        if (writer === "claude-code" || writer === "kiro") scopedLines.push(`- \`${ruleFile(writer, m)}\` — ${scope}`);
        else embedded.push(ruleMarker(outName(m)), `> Scoped rule — ${scope}`, "", body, "");
      }
      if (scopedLines.length || embedded.length) {
        parts.push("## Scoped rules", "", ...scopedLines);
        if (scopedLines.length) parts.push("");
        parts.push(...embedded);
      }
      out.push(await textFile(ctx, GEMINI_MD, parts.join("\n"), t, "rule/*", { keepBom: false }));
    }
    refs.finish();
    return out;
  },
};
