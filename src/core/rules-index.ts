/**
 * Rules index (spec 44 §4): the gate and the reserved prefix.
 */

import { FORGE_SCHEMA_RULES_INDEX } from "../schema/index.js";

/** The rules-index key (spec 44 §4.2). */
export const RULES_INDEX_KEY = "craftar.rules.index";

/**
 * Unanchored regex for the placeholder token `{{craftar.rules.index}}` with optional spaces (spec 44 §4.3).
 * Used by both `RULES_INDEX_LINE` and the misplaced-placeholder check — the one spelling in `src/`.
 */
export const RULES_INDEX_TOKEN = /\{\{\s*craftar\.rules\.index\s*\}\}/;

/**
 * Regex: `{{craftar.rules.index}}` alone on a line (spec 44 §4.2).
 * Used by `plan()` below the gate and by `expandRulesIndex` at the gate.
 */
export const RULES_INDEX_LINE = new RegExp(`^[ \\t]*${RULES_INDEX_TOKEN.source}[ \\t]*$`, "m");

/** Whether the Forge reads the rules index (spec 44 §4.1). */
export function readsRulesIndex(manifest: { schema: number }): boolean {
  return manifest.schema >= FORGE_SCHEMA_RULES_INDEX;
}

/**
 * The warning for a literal `{{craftar.rules.index}}` in a Forge below the gate (spec 44 §4.2).
 * `refs` is the sorted list of `ref (file)` strings.
 */
export function belowGateLiteralWarning(refs: string[]): string {
  return `{{${RULES_INDEX_KEY}}} needs a Forge at schema: ${FORGE_SCHEMA_RULES_INDEX} — left as written in ${refs.join(", ")}`;
}

/**
 * The warning for a value of `craftar.rules.index` set in a layer at the gate (spec 44 §4.2).
 * The value text never appears in the warning.
 */
export function ignoredValueWarning(layer: string): string {
  return `${RULES_INDEX_KEY} is generated by sync — the value in ${layer} is ignored`;
}

/**
 * The warning for rules listed without a description (spec 44 §4.4).
 * `names` is the sorted list of rule names (code-point order, each once).
 */
export function undescribedRulesWarning(names: string[]): string {
  return `${RULES_INDEX_KEY}: no description for rule ${names.join(", ")} — listed by name only`;
}

/**
 * The warning for a placeholder that must stand alone on its line (spec 44 §4.4).
 * `locations` is the sorted list of `path:line` strings.
 */
export function misplacedPlaceholderWarning(locations: string[]): string {
  return `{{${RULES_INDEX_KEY}}} must stand alone on its line — left as written in ${locations.join(", ")}`;
}

/**
 * The warning for a placeholder expanded in rule and steering bodies only (spec 44 §4.4).
 * `paths` is the sorted list of paths where it was left as written.
 */
export function nonBodyPlaceholderWarning(paths: string[]): string {
  return `{{${RULES_INDEX_KEY}}} is expanded in rule and steering bodies only — left as written in ${paths.join(", ")}`;
}
