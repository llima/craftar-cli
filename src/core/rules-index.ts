/**
 * Rules index (spec 44 §4): the gate and the reserved prefix.
 */

import { FORGE_SCHEMA_RULES_INDEX } from "../schema/index.js";

/** The rules-index key (spec 44 §4.2). */
export const RULES_INDEX_KEY = "craftar.rules.index";

/**
 * Regex: `{{craftar.rules.index}}` alone on a line (spec 44 §4.2).
 * Used by `plan()` below the gate and by `expandRulesIndex` at the gate.
 */
export const RULES_INDEX_LINE = /^[ \t]*\{\{\s*craftar\.rules\.index\s*\}\}[ \t]*$/m;

/** Whether the Forge reads the rules index (spec 44 §4.1). */
export function readsRulesIndex(manifest: { schema: number }): boolean {
  return manifest.schema >= FORGE_SCHEMA_RULES_INDEX;
}

/**
 * The warning for a literal `{{craftar.rules.index}}` in a Forge below the gate (spec 44 §4.2).
 * `refs` is the sorted list of `ref (file)` strings.
 */
export function belowGateLiteralWarning(refs: string[]): string {
  return `{{${RULES_INDEX_KEY}}} needs a Forge at schema: ${FORGE_SCHEMA_RULES_INDEX} — left as written in ${refs.join(", ")}`;
}

/**
 * The warning for a value of `craftar.rules.index` set in a layer at the gate (spec 44 §4.2).
 * The value text never appears in the warning.
 */
export function ignoredValueWarning(layer: string): string {
  return `${RULES_INDEX_KEY} is generated by sync — the value in ${layer} is ignored`;
}
