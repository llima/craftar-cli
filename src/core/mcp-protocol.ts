/** A request id as revision 2025-06-18 types it: an error cannot carry `id: null`, so what has none is not answered. */
type Id = string | number;
const isId = (v: unknown): v is Id => typeof v === "string" || typeof v === "number";

const result = (id: Id, value: unknown) => ({ jsonrpc: "2.0", id, result: value });
const error = (id: Id, code: number, message: string) => ({ jsonrpc: "2.0", id, error: { code, message } });
/** A tool's answer: its object as structured content and, serialized, as one text block. */
const toolResult = (value: object) => ({ content: [{ type: "text", text: JSON.stringify(value) }], structuredContent: value });
/** A tool that ran and could not answer: a result, not a protocol error — the server keeps running. */
const toolError = (text: string) => ({ content: [{ type: "text", text }], isError: true });

/** One line of input to the line that answers it (without its newline), or null when nothing is written. */
export async function handleLine(line: string, ctx: McpContext, state: McpState): Promise<string | null> {
  let message: unknown;
  try {
    message = JSON.parse(line);
  } catch {
    return null; // a parse error has no request to answer
  }
  const answer = await handle(message, ctx, state);
  return answer === null ? null : JSON.stringify(answer);
}

/** One parsed message to its answer, or null: a notification, a response, and anything with no usable id. */
export async function handle(message: unknown, ctx: McpContext, state: McpState): Promise<object | null> {
  if (message === null || typeof message !== "object" || Array.isArray(message)) return null;
  const m = message as { id?: unknown; method?: unknown; params?: unknown };
  if (typeof m.method !== "string") {
    // A response: the server sends no request, so it expects none
    if ("result" in m || "error" in m) return null;
    return isId(m.id) ? error(m.id, -32600, "Invalid Request") : null;
  }
  // A notification is never answered; neither is a request whose id could not be echoed
  if (!isId(m.id)) return null;
  const id = m.id;
  if (m.method === "ping") return result(id, {});
  if (m.method === "initialize") {
    // The one revision the server knows, whatever the client asked for: the client decides whether to go on
    state.initialized = true;
    return result(id, { protocolVersion: PROTOCOL_VERSION, capabilities: { tools: {} }, serverInfo: { name: "craftar", version: ctx.version }, instructions: INSTRUCTIONS });
  }
  if (!state.initialized) return error(id, -32600, "not initialized");
  if (m.method === "tools/list")
    return result(id, {
      tools: TOOL_NAMES.map((name) => ({
        name,
        title: TOOLS[name].title,
        description: TOOLS[name].description,
        inputSchema: TOOLS[name].inputSchema,
        annotations: { readOnlyHint: true, destructiveHint: false, idempotentHint: true, openWorldHint: ctx.fetch },
      })),
    });
  if (m.method !== "tools/call") return error(id, -32601, "Method not found");

  const params = (m.params !== null && typeof m.params === "object" ? m.params : {}) as { name?: unknown; arguments?: unknown };
  // The name asked for is not echoed
  if (typeof params.name !== "string" || !(TOOL_NAMES as readonly string[]).includes(params.name)) return error(id, -32602, UNKNOWN_TOOL);
  const name = params.name as ToolName;
  const parsed = TOOLS[name].args.safeParse(params.arguments ?? {});
  // schemaFault names the key — an unrecognized one by the name the caller gave it — and what was expected, never a value
  if (!parsed.success) return error(id, -32602, `invalid arguments for ${name}: ${schemaFault(parsed.error)}`);
  try {
    return result(id, toolResult(await call(name, parsed.data as ToolArguments, ctx)));
  } catch (e) {
    return result(id, toolError(errorText(e)));
  }
}

type ToolArguments = { path?: string; recipe?: string; type?: string };

/**
 * One tool call (spec 35 §4.3–§4.5). The configuration is read ONCE, the pin is checked on that very object, and
 * the Forge is loaded from it — never through `loadWorkspace`, which would read the files again and could load
 * what the check did not see. Nothing but the pin is kept between calls.
 */
async function call(name: ToolName, args: ToolArguments, ctx: McpContext): Promise<object> {
  const seam = { home: ctx.home, git: ctx.git };
  let merged: MergedConfig;
  try {
    merged = await (ctx.readConfig ?? readWorkspaceConfig)(ctx.root);
    const now = pinOf(merged);
    if (now.forge !== ctx.pin.forge || now.ref !== ctx.pin.ref || now.profile !== ctx.pin.profile) throw new Error(PIN_CHANGED);
  } catch (e) {
    // `targets` answers as its command does when a workspace does not load: unmarked, with the reason as a warning
    if (name === "targets") return targetsReport(ctx.root, seam, { reason: errorText(e) });
    throw e;
  }
  if (name === "targets") return targetsReport(ctx.root, seam, { merged });
  if (name === "doctor")
    return workspaceReport(
      await runDoctor({ version: ctx.version, home: ctx.home, workspace: ctx.root, fetch: ctx.fetch, strict: false, registryOff: ctx.registryOff, env: ctx.env, merged, git: ctx.git }),
    );

  const ws = await loadForgeFor(ctx.root, merged, { ...seam, mode: ctx.fetch ? "read" : "no-fetch" });
  const cached = cachedCopyLine(ws, ctx.fetch);
  const loadWarnings = cached === null ? ws.warnings : [cached, ...ws.warnings];

  if (name === "recipes" || name === "ingredients") {
    if (args.type !== undefined) checkType(args.type);
    const context = catalogueContext(ws.forge, { kind: "workspace", config: ws.config });
    const listing = name === "recipes" ? listRecipes(ws.forge, context) : listIngredients(ws.forge, context, { recipe: args.recipe, type: args.type });
    return withLoadWarnings(listing, loadWarnings);
  }

  const p = await plan(ws);
  if (name === "explain") {
    const given = args.path ?? "";
    const file = explainFile(ws, p, statusPath(given));
    if (file === null) throw new Error(notProduced(given, ws.config.profile));
    return { ...file, warnings: loadWarnings };
  }

  const lock = await readLock(ws.root);
  const statuses = await status(ws, p, lock);
  const report = statusReport(ws, p, lock, statuses);
  // The plan's warnings already open with the load's; only the cached-copy line is added
  if (name === "status") return cached === null ? report : { ...report, warnings: [cached, ...report.warnings] };

  // diff: the argument selects a row among the files status() returned — it is never joined into a path
  let rows = statuses;
  if (args.path !== undefined) {
    const only = statusPath(args.path);
    rows = statuses.filter((s) => s.path === only);
    if (rows.length === 0) throw new Error(unmanaged(args.path));
  }
  const files = (await diffReport(ws, rows, { withholdMcp: true })).map((row) => ({
    path: row.path,
    state: row.state,
    added: row.added,
    removed: row.removed,
    // A body is returned for the one named file; the list form carries counts only. The two texts stay here.
    diff: args.path !== undefined && row.note === null ? renderDiff(row.disk ?? "", row.forge ?? "") : null,
    note: row.note,
  }));
  return { files, warnings: loadWarnings, unsetParams: report.unsetParams };
}
