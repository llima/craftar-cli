/*
 * `craftar mcp` (spec 35): the Model Context Protocol, revision 2025-06-18, as a function from one message to
 * its answer. Seven tools that read one workspace — the one the server was started in — with the data the
 * reading commands produce. This module has no I/O of its own (the disk is read by the core functions it calls),
 * never prints and never exits; `src/mcp.ts` is the only place that knows the wire. It imports nothing that
 * writes: `test/mcp-imports.test.ts` holds it to a list.
 */

export const PROTOCOL_VERSION = "2025-06-18";

export const TOOL_NAMES = ["status", "diff", "explain", "recipes", "ingredients", "targets", "doctor"] as const;
export type ToolName = (typeof TOOL_NAMES)[number];

/** `initialize`'s `instructions` (spec 35 §4.7): one fixed paragraph, the same for every workspace. */
export const INSTRUCTIONS =
  "This workspace's AI-coder files (`.claude/`, `.kiro/`, `AGENTS.md`) are generated by Craftar from a shared Forge. Do not edit a generated file by hand: the edit is flagged as drift and the file stops receiving updates until a person resolves it. Use `status` to see what is pending, `explain` to see where a file comes from, and tell the user to run `craftar sync` — these tools read only.";

/** The tool error of a changed pin (spec 35 §4.3). It names the three keys, never a value. */
export const PIN_CHANGED =
  "the Forge or the profile of this workspace changed since craftar mcp started (forge, ref or profile in craftar.yaml / craftar.local.yaml) — restart the server to read the new one";

const UNKNOWN_TOOL = `unknown tool — one of ${TOOL_NAMES.join(", ")}`;

/** What the configuration named at launch, fixed for the life of the process (spec 35 §3): three strings. */
export interface Pin {
  forge: string;
  ref: string | null;
  profile: string;
}

export const pinOf = (merged: MergedConfig): Pin => ({ forge: merged.config.forge, ref: merged.config.ref ?? null, profile: merged.config.profile });

export interface McpContext {
  /** The bound workspace, absolute, resolved once at launch. */
  root: string;
  /** `--fetch`: tool calls load a remote Forge in mode `read`; without it, `no-fetch`. */
  fetch: boolean;
  home: string;
  version: string;
  registryOff: boolean;
  /** The environment `doctor`'s `mcp-env` reads: the one the AI coder gave its MCP servers. */
  env: NodeJS.ProcessEnv;
  pin: Pin;
  /** Test seam, handed to every load, `doctor`'s included. */
  git?: LoadOptions["git"];
  /** Test seam: the one reader of the configuration; absent, `readWorkspaceConfig`. */
  readConfig?: (root: string) => Promise<MergedConfig>;
}

export interface McpState {
  initialized: boolean;
}

/** The launch refusals that need no file read, in the order spec 35 §4.1 checks them; null to go on. */
export function launchRefusal(stdinIsTTY: boolean, hasConfig: boolean, dir: string): string | null {
  if (stdinIsTTY) return "craftar mcp speaks the Model Context Protocol on stdin and stdout — it is started by an AI coder, not typed; see the README";
  if (!hasConfig) return `no craftar.yaml in ${dir} — craftar mcp serves one workspace; start it in one, or pass --workspace`;
  return null;
}

