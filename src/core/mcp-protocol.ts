/** Build the tool error when the consent is for a different forge/ref/profile (spec 40 §5.5). */
export const CONSENT_STALE = (keys: string[]): string =>
  `the write consent of this workspace was given for another ${keys.join(", ")} — a person types craftar mcp allow-writes again to allow the current one`;

/** The tool error when sync needs --fetch for a remote Forge (spec 40 §5.5). */
export const SYNC_NEEDS_FETCH =
  "sync of a remote Forge needs craftar mcp --fetch — the cached copy may be older than the lock's; run craftar sync in a terminal, or restart the server with --fetch";

/** The tool error when the registry cannot be read (spec 40 §5.5). */
export const REGISTRY_UNREADABLE =
  "the registry, where the consent is recorded, does not read — run craftar doctor";

const UNKNOWN_TOOL = `unknown tool — one of ${TOOL_NAMES.join(", ")}`;
const UNKNOWN_TOOL_WITH_WRITES = `unknown tool — one of ${[...TOOL_NAMES, ...WRITE_TOOL_NAMES].join(", ")}`;

export const pinOf = (merged: MergedConfig): Pin => ({ forge: merged.config.forge, ref: merged.config.ref ?? null, profile: merged.config.profile });

export interface McpContext {
  /** The bound workspace, absolute, resolved once at launch. */
  root: string;
  /** `--fetch`: tool calls load a remote Forge in mode `read`; without it, `no-fetch`. */
  fetch: boolean;
  home: string;
  version: string;
  registryOff: boolean;
  /** The environment `doctor`'s `mcp-env` reads: the one the AI coder gave its MCP servers. */
  env: NodeJS.ProcessEnv;
  pin: Pin;
  /** Writing tools: present only with `--allow-writes` (spec 40 §5.3). */
  writers?: McpWriters;
  /** Test seam, handed to every load, `doctor`'s included. */
  git?: LoadOptions["git"];
  /** Test seam: the one reader of the configuration; absent, `readWorkspaceConfig`. */
  readConfig?: (root: string) => Promise<MergedConfig>;
  /** Test seams, handed to `doctor` as they are: absent, the running Node's version and doctor's own probes (`git --version`, `dotnet --version`, `docker compose version --short`). */
  nodeVersion?: DoctorOptions["nodeVersion"];
  gitVersion?: DoctorOptions["gitVersion"];
  dotnetVersion?: DoctorOptions["dotnetVersion"];
  dockerRunner?: DoctorOptions["dockerRunner"];
}

export interface McpState {
  initialized: boolean;
}

/** The launch refusals that need no file read, in the order spec 35 §4.1 checks them; null to go on. */
export function launchRefusal(stdinIsTTY: boolean, hasConfig: boolean, dir: string): string | null {
  if (stdinIsTTY) return "craftar mcp speaks the Model Context Protocol on stdin and stdout — it is started by an AI coder, not typed; see the README";
  if (!hasConfig) return `no craftar.yaml in ${dir} — craftar mcp serves one workspace; start it in one, or pass --workspace`;
  return null;
}

