/*
 * What the reading commands answer, as data (spec 35 §5.1): one builder per shape, called by the CLI, by
 * `craftar mcp` and by anything else that shows the same thing. Nothing here prints, and none of them selects,
 * normalizes or refuses a path — each caller keeps its own rule.
 */

/** The one test of which states `diff` shows — the states `sync --check` refuses. */
export function diffShows(state: FileState): boolean {
  return state !== "unchanged" && state !== "adopt";
}

/** Spec 27 Ruling 4: the on-disk content of the example file is never shown. No indentation: the caller's. */
export const EXAMPLE_CONTENT_HIDDEN = "content not shown: an example file may hold a value typed by hand";
/** Spec 35 §4.5: what `craftar mcp` says in place of the disk side of a hand-touched MCP file. */
export const MCP_CONTENT_HIDDEN = "content not shown: an MCP configuration file may hold a value typed by hand";

/** A path as the user may type it, to the spelling `status` prints: forward slashes, no leading `./`. */
export const statusPath = (p: string) => p.replace(/\\/g, "/").replace(/^\.\//, "");

/** `explain`'s refusal: the Forge does not produce this path for the profile. */
export const notProduced = (p: string, profile: string) => `${p} is not produced by the Forge for profile ${profile}`;

/** Why sync leaves a file alone, for the three states it skips. */
export function explainSkip(s: Pick<FileStatus, "state" | "path" | "escapes">): string {
  if (s.escapes) return escapeSummary([{ path: s.path, escapes: s.escapes }]);
  switch (s.state) {
    case "drift":
      return "hand-edited since last sync — `craftar drift show <path>`, then `craftar drift discard` or `craftar drift promote`";
    case "collision":
      return "exists but was never generated by craftar and differs from the Forge — rename it or import it";
    case "orphan-drift":
      return "no longer produced by the Forge but hand-edited — kept; `craftar drift discard <path>` removes it, or delete it yourself";
    default:
      return "";
  }
}

/** A file's text as a diff compares it: LF, no BOM; null when it cannot be read. */
export async function readText(p: string): Promise<string | null> {
  try {
    return toLf(stripBom(await fs.readFile(p, "utf8")));
  } catch {
    return null;
  }
}

/** The document `craftar status --json` prints (spec 13 §4.1, spec 29 §4.1). */
export interface StatusReport {
  forge: {
    kind: "path" | "remote";
    source: string;
    ref: string | null;
    defaultBranch: string | null;
    commit: string | null;
    lockCommit: string | null;
    fetched: boolean;
  };
  statuses: Array<Omit<FileStatus, "planned">>;
  warnings: string[];
  unsetParams: UnsetParam[];
}

/** Spec 48 §4.3: the reason is built from the rows, since `plan()` does not see the lock. No key is added for it. */
export function withEscapeLine(warnings: string[], statuses: ReadonlyArray<Pick<FileStatus, "path" | "escapes">>): string[] {
  const rows = escapingRows(statuses);
  return rows.length ? [...warnings, escapeSummary(rows)] : warnings;
}

export function statusReport(ws: Workspace, p: Plan, lock: Lock | null, statuses: FileStatus[]): StatusReport {
  const o = ws.origin;
  return {
    forge: {
      kind: o.kind,
      source: o.source,
      ref: o.ref,
      defaultBranch: o.defaultBranch,
      commit: ws.forge.commit,
      lockCommit: lock?.forge.commit ?? null,
      fetched: o.fetched,
    },
    // The planned buffer never leaves the process: dropped here, once, for every reader of the document.
    statuses: statuses.map(({ planned, escapes, ...s }) => s),
    warnings: withEscapeLine(p.warnings, statuses),
    unsetParams: unsetDeclared(p),
  };
}

/** One file `sync --check` refuses, as `diff` decides it: a note in place of a body, or the two texts to render. */
export interface DiffRow {
  path: string;
  state: FileStatus["state"];
  /** Lines the Forge's side adds and removes; null when a note stands in for the body. */
  added: number | null;
  removed: number | null;
  note: string | null;
  /** The disk side and the Forge's side, LF and without a BOM; both null when there is a note. */
  disk: string | null;
  forge: string | null;
}

/**
 * What `diff` shows for each row in a state `sync --check` refuses (spec 19 §3.2: `unchanged` and `adopt` are
 * skipped). It never renders: the caller owns the header lines and the paint. `withholdMcp` widens the one
 * withholding of spec 27 Ruling 4 — the example file — to every file tagged `mcp/*`, for a reader that is a model
 * (spec 35 §4.5). The disk is read at the row's path, never at one a caller typed.
 */
export async function diffReport(ws: Pick<Workspace, "root">, rows: FileStatus[], opts: { withholdMcp: boolean }): Promise<DiffRow[]> {
  const out: DiffRow[] = [];
  for (const s of rows) {
    if (!diffShows(s.state)) continue;
    const noted = (note: string): DiffRow => ({ path: s.path, state: s.state, added: null, removed: null, note, disk: null, forge: null });
    if (s.escapes) {
      // Nothing of what lies behind the link is read: a header and a note, on every surface.
      out.push(noted(`content not shown: ${escapeReason(s.escapes)}`));
      continue;
    }
    if (s.state === "orphan-drift") {
      // No body: sync keeps this file
      out.push(noted(explainSkip(s)));
      continue;
    }
    // Only where a hand has touched the file: in `update` and `orphan` the disk side is what craftar wrote.
    if (s.state === "drift" || s.state === "collision") {
      if (opts.withholdMcp && mcpTagged(s)) {
        out.push(noted(MCP_CONTENT_HIDDEN));
        continue;
      }
      if (s.path === EXAMPLE_SETTINGS) {
        out.push(noted(EXAMPLE_CONTENT_HIDDEN));
        continue;
      }
    }
    const disk = (await readText(path.join(ws.root, s.path))) ?? "";
    // An orphan is the removal of the whole file
    const forge = s.state === "orphan" || !s.planned ? "" : toLf(stripBom(s.planned.content.toString("utf8")));
    const ops = diffOps(disk, forge);
    out.push({
      path: s.path,
      state: s.state,
      added: ops.filter((o) => o.kind === "add").length,
      removed: ops.filter((o) => o.kind === "del").length,
      note: null,
      disk,
      forge,
    });
  }
  return out;
}

/**
 * What an `orphan-drift` file holds, for a surface that shows it before a discard (spec 40 §6.5, `drift show <path>`):
 * the whole body read from disk, or — for EXAMPLE_SETTINGS, whose content is never shown — `{ body: null, note:
 * EXAMPLE_CONTENT_HIDDEN }`. The one reader of such a body.
 */
export async function orphanDriftBody(root: string, s: Pick<FileStatus, "path" | "state" | "escapes">): Promise<{ body: string | null; note: string | null }> {
  if (s.state !== "orphan-drift") throw new Error("state must be orphan-drift");
  if (s.escapes) return { body: null, note: `content not shown: ${escapeReason(s.escapes)}` };
  if (s.path === EXAMPLE_SETTINGS) return { body: null, note: EXAMPLE_CONTENT_HIDDEN };
  return { body: (await readText(path.join(root, s.path))) ?? "", note: null };
}

/** What `craftar explain` says about one generated file, as data (spec 35 §4.5). */
export interface ExplainedFile {
  path: string;
  target: PlannedFile["target"];
  ingredient: string;
  /** Where an imported ingredient came from; null when it was not imported, or the file is no single ingredient's. */
  origin: { workspace: string; path: string } | null;
  /** The recipes that bring the ingredient; null for a file that is no single ingredient's (AGENTS.md, the MCP files). */
  via: string[] | null;
  sections: Array<{ name: string; layer: SectionLayer }>;
  params: Array<{ key: string; layer: ParamLayer }>;
  profile: string;
  recipes: string[];
  hash: string;
  /** At Forge schema 8 and above only (spec 51 §4.4): where the file's ingredient lives — null for a file built from several. */
  scope?: "forge" | "profile" | null;
  /** Its folder, Forge-relative and POSIX, so a cached tree never prints its entry's name; null as `scope` is. */
  dir?: string | null;
}

/** The planned file at `file`, compared as given (the caller normalizes); null when the Forge does not produce it. */
export function explainFile(ws: Workspace, p: Plan, file: string): ExplainedFile | null {
  const f = p.files.find((x) => x.path === file);
  if (!f) return null;
  // AGENTS.md (rule/*) and the MCP files (mcp/*) are not one ingredient: nothing resolved has their ref.
  const ing = p.resolution.ingredients.find((i) => i.ref === f.ingredient);
  return {
    path: f.path,
    target: f.target,
    ingredient: f.ingredient,
    origin: ing?.meta.origin ? { workspace: ing.meta.origin.workspace, path: ing.meta.origin.path } : null,
    via: ing ? [...ing.via] : null,
    sections: (p.sections.get(f.ingredient) ?? [])
      .filter((x) => !x.targets || (x.targets as readonly string[]).includes(f.target))
      .map((x) => ({ name: x.name, layer: x.layer })),
    params: (p.params.get(f.ingredient) ?? []).map((x) => ({ key: x.key, layer: x.layer })),
    profile: ws.config.profile,
    recipes: [...p.resolution.recipes],
    hash: hashNormalized(f.content),
    ...(readsProfileLocal(ws.forge.manifest) ? sourceOf(ws, ing) : {}),
  };
}

/** Where a file's one ingredient lives (spec 51 §4.4). */
function sourceOf(ws: Workspace, ing: { ref: string; dir: string } | undefined): { scope: "forge" | "profile" | null; dir: string | null } {
  if (!ing) return { scope: null, dir: null };
  const dir = path.relative(ws.forge.root, ing.dir).split(path.sep).join("/");
  const local = ws.forge.locals.get(ws.config.profile)?.ingredients.get(ing.ref as never);
  return { scope: local && local.dir === ing.dir ? "profile" : "forge", dir };
}

/** The document `craftar targets --json` prints (spec 16 §4.4). */
export type TargetsReport = ListTargetsResult & { warnings: string[] };

/**
 * The capability matrix with the targets a workspace uses marked. `input` is the configuration to load from
 * (never fetched: `no-fetch`), a reason not to load — worded as a failed load is — or null for no workspace at
 * all: the matrix unmarked, no warning. It never throws for a workspace that does not load or resolve.
 */
export async function targetsReport(
  root: string,
  opts: Pick<LoadOptions, "home" | "git">,
  input: { merged: MergedConfig } | { reason: string } | null,
): Promise<TargetsReport> {
  if (input === null) return { ...listTargets(null), warnings: [] };
  const notShown = (why: string) => ({ ...listTargets(null), warnings: [`targets in use not shown: ${why}`] });
  if ("reason" in input) return notShown(input.reason);
  try {
    const ws = await loadForgeFor(root, input.merged, { ...opts, mode: "no-fetch" });
    return { ...listTargets(resolve(ws.forge, ws.config).targets), warnings: [] };
  } catch (e) {
    // Load or resolve failed — a warning, not an error
    return notShown(errorText(e));
  }
}

/**
 * For a reader started without `--fetch` (`craftar mcp`, spec 35 §4.4): the line that says a remote Forge was read
 * from its cached copy, so an answer for a Forge that has moved is never silent. Null when the caller fetches (the
 * fallback warning is then the signal), for a path Forge, and for a full-SHA `ref`, which cannot go stale.
 */
export function cachedCopyLine(ws: Pick<Workspace, "origin" | "forge">, fetch: boolean): string | null {
  const o = ws.origin;
  if (fetch || o.kind !== "remote" || (o.ref !== null && FULL_SHA.test(o.ref))) return null;
  return `Forge ${o.source} read from the copy cached ${o.fetchedAt ?? "(time unknown)"} (commit ${ws.forge.commit?.slice(0, 8) ?? "no git"}) — craftar mcp was started without --fetch`;
}

/** The header line naming a remote Forge (spec 13 §4.1); null for a path Forge, whose headers keep their shape. */
export function forgeLine(ws: Workspace, lock: Lock | null): string | null {
  const o = ws.origin;
  if (o.kind !== "remote") return null;
  const commit = ws.forge.commit;
  const at = o.ref ?? `${o.defaultBranch} (default branch)`;
  const moved = lock?.forge.commit && commit && lock.forge.commit !== commit ? ` · lock ${lock.forge.commit.slice(0, 8)}` : "";
  return `  forge ${o.source} @ ${at} ${commit?.slice(0, 8) ?? "no git"}${moved}`;
}

/**
 * Spec 22's line: what the next sync would do (also `init --no-sync`, spec 23 §4.4).
 * Uses `countStates` from `src/core/impact.ts`; a new `FileState` does not compile until it is
 * placed in `FILE_STATE_ORDER_MAP` there. A plan with unset declared parameters has no next sync
 * to count: the line says it is refused (spec 29 §4.1).
 */
export function nextSyncLine(st: FileStatus[], unset: UnsetParam[]): string {
  if (unset.length) return `next sync: ${unsetRefused(unset)}`;
  const escaping = escapingRows(st);
  if (escaping.length) return `next sync: refused — ${escapeSummary(escaping)}`;
  const counts = countStates(st).map(([k, n]) => `${n} ${k}`);
  return `next sync: ${counts.length ? `${counts.join(", ")} — run \`craftar sync\`` : "nothing to sync"}`;
}
